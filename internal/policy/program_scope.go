package policy

import (
	"crypto/sha256"
	"fmt"
	"net/netip"
	"strings"
	"time"
)

func CanonicalFilter(f Filter) Filter {
	if f.InterfaceName != "" {
		f.InterfaceIndex = 0
	}
	if f.Remote != "" {
		if ep, err := netip.ParseAddrPort(f.Remote); err == nil {
			f.RemoteAddress = ep.Addr().Unmap().String()
			f.RemotePort = ep.Port()
			f.Remote = ""
		}
	}
	if f.RemoteAddress == "" {
		f.RemoteAddress = "*"
	}
	if a, err := netip.ParseAddr(f.RemoteAddress); err == nil {
		f.RemoteAddress = a.Unmap().String()
	} else if p, err := netip.ParsePrefix(f.RemoteAddress); err == nil {
		f.RemoteAddress = p.Masked().String()
		if p.Bits() == p.Addr().BitLen() {
			f.RemoteAddress = p.Addr().Unmap().String()
		}
	}
	return f
}

// ProgramScope is the exact configured scope, excluding the historical stamp.
func (r Rule) ProgramScope() Filter {
	f := CanonicalFilter(r.Filter)
	if r.FollowsUpdates() {
		f.Revision = ""
	}
	return f
}

// RememberOverlayIDPrefix is reserved for decisions generated by Remember.
const RememberOverlayIDPrefix = "user:remember:"

// RememberAskPrefix binds a remembered choice to the Ask that created it.
func RememberAskPrefix(askID string) string {
	hash := sha256.Sum256([]byte(askID))
	return fmt.Sprintf("%s%x:", RememberOverlayIDPrefix, hash[:12])
}

// LatestProgramRules removes only choices superseded for their whole remaining
// lifetime. A remembered choice can mask the original Ask, which must stay saved.
func LatestProgramRules(rules []Rule) []Rule {
	out := make([]Rule, 0, len(rules))
	for _, r := range rules {
		superseded := false
		if r.FollowsUpdates() {
			for _, newer := range rules {
				// Keep saved rules under a Remember override so they can
				// resume after deletion or expiry.
				if strings.HasPrefix(newer.ID, RememberOverlayIDPrefix) {
					continue
				}
				if newer.FollowsUpdates() && newer.ProgramScope() == r.ProgramScope() && newer.Created.After(r.Created) && (newer.Expires.IsZero() || (!r.Expires.IsZero() && !newer.Expires.Before(r.Expires))) {
					superseded = true
					break
				}
			}
		}
		if !superseded {
			out = append(out, r)
		}
	}
	return out
}

// CurrentProgramRules gives the newest unexpired setting precedence within
// one exact program scope. Disabling it does not revive an older choice.
func CurrentProgramRules(rules []Rule, now time.Time) []Rule {
	return programRules(rules, now, false)
}

// EffectiveProgramRules also exposes the retained Ask under a disabled
// application-wide remembered choice before expiry. Keep the disabled choice in the
// result so inventory can describe both rules and the quick setter keeps its target.
func EffectiveProgramRules(rules []Rule, now time.Time) []Rule {
	return programRules(rules, now, true)
}

func programRules(rules []Rule, now time.Time, restoreAsk bool) []Rule {
	latest := map[Filter]time.Time{}
	for _, r := range rules {
		if !r.FollowsUpdates() || (!r.Expires.IsZero() && !now.Before(r.Expires)) {
			continue
		}
		k := r.ProgramScope()
		if t, ok := latest[k]; !ok || r.Created.After(t) {
			latest[k] = r.Created
		}
	}
	out := make([]Rule, 0, len(rules))
	for _, r := range rules {
		if !r.FollowsUpdates() {
			out = append(out, r)
			continue
		}
		scope := r.ProgramScope()
		if r.Created.Before(latest[scope]) {
			continue
		}
		if restoreAsk && r.Disabled && (r.Action == "allow" || r.Action == "block") &&
			(r.Expires.IsZero() || now.Before(r.Expires)) && strings.HasPrefix(r.ID, RememberOverlayIDPrefix) {
			if ask := retainedApplicationAsk(r, scope, rules, now); ask != nil {
				out = append(out, *ask)
			}
		}
		out = append(out, r)
	}
	return out
}

// Revive only the proven source Ask, and only when no other current record
// would take its place if the disabled choice were removed.
func retainedApplicationAsk(choice Rule, scope Filter, rules []Rule, now time.Time) *Rule {
	if scope.NetworkZone != "" || scope.Protocol != "*" || scope.RemoteAddress != "*" ||
		scope.Remote != "" || scope.LocalPort != 0 || scope.RemotePort != 0 || scope.LocalAddress != "" ||
		scope.InterfaceIndex != 0 || scope.InterfaceName != "" || scope.PeerService != (PeerService{}) {
		return nil
	}
	var prior *Rule
	ambiguous := false
	for i := range rules {
		r := &rules[i]
		if r.ID == choice.ID || !r.FollowsUpdates() || (!r.Expires.IsZero() && !now.Before(r.Expires)) ||
			r.ProgramScope() != scope {
			continue
		}
		if !r.Created.Before(choice.Created) {
			return nil
		}
		if prior == nil || r.Created.After(prior.Created) {
			prior = r
			ambiguous = false
		} else if r.Created.Equal(prior.Created) {
			ambiguous = true
		}
	}
	if prior == nil || ambiguous || prior.Disabled || prior.Action != "ask" || !strings.HasPrefix(choice.ID, RememberAskPrefix(prior.ID)) {
		return nil
	}
	return prior
}
