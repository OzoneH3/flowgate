#!/usr/bin/env python3
"""One-time root setup for account-specific, passwordless local FlowGate updates.

Local build installation is root-equivalent trust in the selected account.
This command does not install a release or change protection state.
"""
import argparse
import os
import pathlib
import pwd
import re
import subprocess
import sys
import tempfile

sys.dont_write_bytecode = True
ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'scripts/lib'))
from update_and_start import STAGE_INSTALL, STAGE_PREFLIGHT, UPDATE_HELPER

SUDOERS = pathlib.Path('/etc/sudoers.d/flowgate-local-update')
OPERATIONS = ('check', 'preflight', 'install', 'configure-wine')


def helper_source(uid):
    commands = {'preflight': STAGE_PREFLIGHT, 'install': STAGE_INSTALL,
                'configure-wine': (ROOT / 'scripts/lib/configure_wine_discovery.py').read_text()}
    return '''#!/usr/bin/python3 -I
# Root-owned FlowGate local update helper. Generated by setup-passwordless-update.py.
import os, subprocess, sys
EXPECTED_UID = %r
COMMANDS = %r

def main():
    if os.geteuid() != 0 or os.environ.get('SUDO_UID') != str(EXPECTED_UID):
        raise SystemExit('FlowGate update: unauthorized caller')
    if len(sys.argv) != 2 or sys.argv[1] not in ('check', *COMMANDS):
        raise SystemExit('FlowGate update: invalid operation')
    if sys.argv[1] == 'check':
        print('flowgate-local-update-v2')
        return 0
    # Never execute caller-supplied command strings or import from their tree.
    # The selected bundle itself is trusted root code, as with a sudo install.
    payload = sys.stdin.buffer.read(512 * 1024 * 1024 + 1) if sys.argv[1] != 'configure-wine' else b''
    if len(payload) > 512 * 1024 * 1024:
        raise SystemExit('FlowGate update: bundle too large')
    env = {'PATH': '/usr/sbin:/usr/bin:/sbin:/bin', 'LANG': 'C.UTF-8',
           'HOME': '/root', 'SUDO_UID': str(EXPECTED_UID)}
    return subprocess.run(['/usr/bin/python3', '-I', '-c', COMMANDS[sys.argv[1]]],
                          input=payload, env=env, cwd='/').returncode

if __name__ == '__main__':
    sys.exit(main())
''' % (uid, commands)


def sudoers_source(name):
    if not re.fullmatch(r'[a-z_][a-z0-9_-]*[$]?', name):
        raise ValueError('Unsupported sudoers account name')
    commands = ', '.join(UPDATE_HELPER + ' ' + op for op in OPERATIONS)
    return '# FlowGate local-source updates: this account can install root code.\n' + name + ' ALL=(root) NOPASSWD: ' + commands + '\n'


def safe_parent(path):
    for p in reversed([path, *path.parents]):
        if not p.exists() and not p.is_symlink():
            p.mkdir(mode=0o755)
        st = p.lstat()
        if p.is_symlink() or not p.is_dir() or st.st_uid != 0 or st.st_mode & 0o022:
            raise RuntimeError('Unsafe installation directory: ' + str(p))


def write_atomic(path, data, mode, validate=False):
    safe_parent(path.parent)
    if path.is_symlink():
        raise RuntimeError('Refusing symlink: ' + str(path))
    fd, tmp = tempfile.mkstemp(prefix='.flowgate-update-', dir=path.parent)
    try:
        with os.fdopen(fd, 'w') as f:
            os.fchmod(f.fileno(), mode)
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        if validate:
            subprocess.run(['/usr/sbin/visudo', '-cf', tmp], check=True)
        os.replace(tmp, path)
    finally:
        pathlib.Path(tmp).unlink(missing_ok=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--user', help='Account allowed to update; defaults to the invoking sudo user')
    args = parser.parse_args()
    if os.geteuid() != 0:
        parser.error('Run this one-time setup with sudo /usr/bin/python3 -I')
    account = pwd.getpwnam(args.user) if args.user else pwd.getpwuid(int(os.environ.get('SUDO_UID', '0')))
    if account.pw_uid == 0:
        parser.error('Select a non-root desktop account with --user')
    rule = sudoers_source(account.pw_name)
    # Do not silently replace another account's authorization.
    if SUDOERS.exists() and SUDOERS.read_text() != rule:
        raise RuntimeError('An existing update authorization differs; review it before replacing')
    write_atomic(pathlib.Path(UPDATE_HELPER), helper_source(account.pw_uid), 0o755)
    write_atomic(SUDOERS, rule, 0o440, validate=True)
    print('Passwordless FlowGate updates enabled for ' + account.pw_name)
    print('Local builds are trusted root code. No release installed; protection unchanged.')


if __name__ == '__main__':
    main()
